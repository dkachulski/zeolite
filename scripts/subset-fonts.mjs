/**
 * Builds the site's Roboto fonts: for each weight and style the design uses,
 * and each @fontsource subset (Latin, Cyrillic, ...) whose range holds a
 * character the site shows, a WOFF2 with only those characters, plus their
 * @font-face rules: src/styles/fonts.css for regular and bold, the only
 * weights on the first screen, and src/styles/fonts-deferred.css for the
 * rest, which site.ts adds after the page has loaded so they never delay
 * the first paint. The characters are read
 * from everything under src/ (translations, components, scripts, styles),
 * with all printable ASCII always kept, so files are about a third of the
 * full subsets and new wording is covered on the next build.
 *
 * Runs before every dev and build (predev, prebuild): npm run fonts
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import subsetFont from "subset-font";

const FONTSOURCE = "node_modules/@fontsource/roboto";
const OUTPUT = "src/assets/fonts";
const CSS = "src/styles/fonts.css";
const DEFERRED_CSS = "src/styles/fonts-deferred.css";
// "critical" faces are used on the first screen at every width.
const FACES = [
  { weight: 300, style: "normal" },
  { weight: 400, style: "normal", critical: true },
  { weight: 400, style: "italic" },
  { weight: 500, style: "normal" },
  { weight: 700, style: "normal", critical: true },
  { weight: 700, style: "italic" },
  { weight: 900, style: "normal" },
];
// Generated files would only feed the set back to itself.
const SKIP = new Set(["src/styles/fonts.css", "src/styles/fonts-deferred.css", "src/components/brand-glyphs.json"]);

const sourceFiles = directory =>
  readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(path);
    return /\.(json|astro|ts|css)$/.test(entry.name) && !SKIP.has(path) ? [path] : [];
  });

const codePoints = new Set();
for (const file of sourceFiles("src")) {
  for (const character of readFileSync(file, "utf8")) {
    const point = character.codePointAt(0);
    if (point >= 0x20) codePoints.add(point);
  }
}
for (let point = 0x20; point < 0x7f; point++) codePoints.add(point);
// Spaces a browser may insert when formatting numbers.
for (const point of [0xa0, 0x2009, 0x202f]) codePoints.add(point);

const parseRange = range =>
  range.split(",").map(part => {
    const [start, end] = part.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(start, 16), parseInt(end ?? start, 16)];
  });
const inRange = (point, ranges) => ranges.some(([start, end]) => point >= start && point <= end);

// @fontsource lists each subset with its unicode-range in <weight>[-italic].css.
function subsets({ weight, style }) {
  const css = readFileSync(`${FONTSOURCE}/${weight}${style === "italic" ? "-italic" : ""}.css`, "utf8");
  return [...css.matchAll(/\/\* roboto-([a-z-]+)-\d+-(?:normal|italic) \*\/[\s\S]*?unicode-range: ([^;]+);/g)].map(
    ([, subset, range]) => ({ subset, range: range.trim(), ranges: parseRange(range) }),
  );
}

rmSync(OUTPUT, { recursive: true, force: true });
mkdirSync(OUTPUT, { recursive: true });

const rules = { critical: [], deferred: [] };
let total = 0;
for (const face of FACES) {
  for (const { subset, range, ranges } of subsets(face)) {
    const used = [...codePoints].filter(point => inRange(point, ranges));
    if (!used.length) continue;
    const name = `roboto-${subset}-${face.weight}-${face.style}`;
    const source = readFileSync(`${FONTSOURCE}/files/${name}.woff`);
    const woff2 = await subsetFont(source, String.fromCodePoint(...used), { targetFormat: "woff2" });
    writeFileSync(`${OUTPUT}/${name}.woff2`, woff2);
    total += woff2.length;
    rules[face.critical ? "critical" : "deferred"].push(`@font-face {
  font-family: "Roboto";
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url("../assets/fonts/${name}.woff2") format("woff2");
  unicode-range: ${range};
}`);
  }
}

const header = note => `/* Generated by scripts/subset-fonts.mjs (npm run fonts); do not edit.
   Roboto, self-hosted from @fontsource/roboto, each subset cut down to the
   characters the site shows. ${note} */
`;
writeFileSync(CSS, `${header("Regular and bold, used on the first screen.")}${rules.critical.join("\n")}\n`);
writeFileSync(
  DEFERRED_CSS,
  `${header("The other weights, added by site.ts after the page has loaded.")}${rules.deferred.join("\n")}\n`,
);
const count = rules.critical.length + rules.deferred.length;
console.log(`fonts: ${count} files (${rules.critical.length} on first paint), ${Math.round(total / 1024)} KB, ${codePoints.size} characters`);
